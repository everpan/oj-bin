//! `oj mcp`：离线生成**零依赖** Node.js stdio MCP server（线路 A，spec 2026-10-30）。
//!
//! 与线路 B（serve 内建 `{base}/mcp`）同源不同形：tool 列表与净化规则共享
//! `serve::openapi::generate` + `serve::mcp::spec_to_tools`，产物是一份自包含 JS
//! （内嵌 tool 数组 + dispatch 表 + spec_hash），任何 MCP client 以 stdio 挂
//! `<node> mcp-server.js` 即用——适合「服务在别处/不给直连」的分发场景。
//!
//! 模板纪律（spec 线路 A + R9，逐字）：NDJSON stdio；stdout 纯净（诊断全走
//! `console.error`）；方法集 initialize（协商+capabilities+serverInfo）/ping/
//! tools/list/tools/call；通知不回写；batch → -32600；path 单段 `encodeURIComponent`、
//! catch-all 走 `decodeURI` 原样插入；query 值 String() 化；解析**不 gate 在
//! res.ok**（envelope 检测与 HTTP 状态解耦）；`text/event-stream` 或
//! `AbortSignal.timeout(30s)` → isError「streaming endpoint, not supported via MCP」；
//! token/base 全走 `process.env.OJ_TOKEN`/`OJ_BASE`；`redirect: "manual"`（3xx 当
//! 错误）；非 localhost `http://` → stderr 明文 Bearer 警告；租户头名（非密钥）自
//! `-c config.yaml` 内嵌，值取 `OJ_TENANT` env，未配置租户则不生成该头。

use serde_json::{Value, json};
use std::path::PathBuf;

use crate::args::McpArgs;

/// stdio server 模板。`__TOKEN__` 占位替换（不引模板引擎）；JS 里的 `{}` 因此
/// 无需转义。ASCII only。
const TEMPLATE: &str = r#"#!/usr/bin/env node
// Generated by `oj mcp` -- do not edit.
// api base path: __BASE_PATH__   spec_hash: __HASH__
// regen: oj mcp -c <config> [-d <dir>|--module-root <root>] [--base B] [-o <file>]
// env: OJ_BASE (required, e.g. http://localhost:9778) | OJ_TOKEN (Bearer, optional)
//      OJ_TENANT (tenant header value, only if the server config declares a tenant header)
"use strict";

const SUPPORTED = ["2024-11-05", "2025-03-26", "2025-06-18"];
const SPEC_HASH = "__HASH__";
const SERVER_NAME = "oj-mcp-__HASH8__";
const TOOLS = __TOOLS_JSON__;
const DISPATCH = __DISPATCH_JSON__;
__TENANT_HEADER__

const BASE_URL = process.env.OJ_BASE;
if (!BASE_URL) {
  console.error("oj mcp: OJ_BASE is required (e.g. http://localhost:9778)");
  process.exit(2);
}
if (/^http:\/\//.test(BASE_URL) && !/^http:\/\/(localhost|127\.0\.0\.1|\[::1\])(:|\/|$)/.test(BASE_URL)) {
  console.error("oj mcp: WARNING - OJ_BASE is plain http:// on a non-localhost host;" +
    " the Bearer token (OJ_TOKEN) will travel in cleartext.");
}
const TOKEN = process.env.OJ_TOKEN || "";
let tenantWarned = false;

function reply(r) { process.stdout.write(JSON.stringify(r) + "\n"); }

function fillPath(tmpl, args, catchAll) {
  const segs = [];
  for (const seg of tmpl.split("/")) {
    if (!seg) continue;
    const m = /^\{(.+)\}$/.exec(seg);
    if (m) {
      const name = m[1];
      const v = args == null ? undefined : args[name];
      if (v === undefined || v === null) {
        throw { code: -32602, message: "missing path argument: " + name };
      }
      segs.push(catchAll.has(name) ? decodeURI(String(v)) : encodeURIComponent(String(v)));
    } else {
      segs.push(seg);
    }
  }
  return "/" + segs.join("/");
}

function buildQuery(args) {
  const qs = new URLSearchParams();
  if (args && typeof args.query === "object" && args.query) {
    for (const [k, v] of Object.entries(args.query)) qs.append(k, String(v));
  }
  const s = qs.toString();
  return s ? "?" + s : "";
}

async function callTool(name, args) {
  const d = DISPATCH[name];
  if (!d) return { isError: true, content: [{ type: "text", text: "unknown tool: " + name }] };
  let path;
  try {
    path = fillPath(d.path, args, new Set(d.catchAll || []));
  } catch (e) {
    return { isError: true, content: [{ type: "text", text: e.message } ] };
  }
  const headers = { accept: "application/json" };
  let body;
  if (args && args.body !== undefined) {
    headers["content-type"] = "application/json";
    body = JSON.stringify(args.body);
  }
  if (TOKEN) headers["authorization"] = "Bearer " + TOKEN;
  if (TENANT_HEADER) {
    const t = process.env.OJ_TENANT;
    if (t) headers[TENANT_HEADER] = t;
    else if (!tenantWarned) {
      tenantWarned = true;
      console.error("oj mcp: tenant header " + TENANT_HEADER + " configured but OJ_TENANT is not set" +
        " - sending without tenant header");
    }
  }
  let res;
  try {
    res = await fetch(BASE_URL + path + buildQuery(args), {
      method: d.method.toUpperCase(),
      headers,
      body,
      redirect: "manual",
      signal: AbortSignal.timeout(30000),
    });
  } catch (e) {
    return { isError: true, content: [{ type: "text", text: "transport error: " + (e && e.message ? e.message : e) }] };
  }
  const ct = res.headers.get("content-type") || "";
  if (ct.includes("text/event-stream")) {
    try { if (res.body) await res.body.cancel(); } catch (_) { /* best effort */ }
    return { isError: true, content: [{ type: "text", text: "streaming endpoint, not supported via MCP" }] };
  }
  const text = await res.text();
  let parsed = null;
  try { parsed = JSON.parse(text); } catch (_) { /* raw text below */ }
  if (parsed && typeof parsed === "object" && typeof parsed.code === "number" && typeof parsed.msg === "string") {
    if (parsed.code === 0) {
      const data = parsed.data === undefined ? null : parsed.data;
      return {
        content: [{ type: "text", text: typeof data === "string" ? data : JSON.stringify(data, null, 2) }],
        structuredContent: data,
      };
    }
    return { isError: true, content: [{ type: "text", text: parsed.msg }] };
  }
  return { content: [{ type: "text", text }] };
}

async function dispatch(msg) {
  if (Array.isArray(msg)) {
    // MCP 2025-06-18 移除 batch：-32600（非法请求）。
    return { jsonrpc: "2.0", id: null, error: { code: -32600, message: "batch not supported" } };
  }
  if (!msg || msg.jsonrpc !== "2.0" || typeof msg.method !== "string") {
    return { jsonrpc: "2.0", id: (msg && msg.id) || null, error: { code: -32600, message: "invalid request" } };
  }
  const isNotify = msg.id === undefined;
  const err = (code, message) => ({ jsonrpc: "2.0", id: msg.id || null, error: { code, message } });
  switch (msg.method) {
    case "initialize": {
      if (isNotify) return undefined;
      const pv = msg.params && msg.params.protocolVersion;
      const negotiated = SUPPORTED.indexOf(pv) >= 0 ? pv : SUPPORTED[SUPPORTED.length - 1];
      return {
        jsonrpc: "2.0",
        id: msg.id,
        result: {
          protocolVersion: negotiated,
          capabilities: { tools: {} },
          serverInfo: { name: SERVER_NAME, version: SPEC_HASH },
        },
      };
    }
    case "ping":
      return isNotify ? undefined : { jsonrpc: "2.0", id: msg.id, result: {} };
    case "tools/list":
      return isNotify ? undefined : { jsonrpc: "2.0", id: msg.id, result: { tools: TOOLS } };
    case "tools/call": {
      const r = await callTool(msg.params && msg.params.name, msg.params && msg.params.arguments);
      return isNotify ? undefined : { jsonrpc: "2.0", id: msg.id, result: r };
    }
    default:
      if (msg.method.lastIndexOf("notifications/", 0) === 0) return undefined;
      return err(-32601, "method not found: " + msg.method);
  }
}

const rl = require("node:readline").createInterface({ input: process.stdin });
rl.on("line", (line) => {
  (async () => {
    let msg = null;
    try { msg = JSON.parse(line); } catch (_) { /* parse error below */ }
    if (msg === null) {
      reply({ jsonrpc: "2.0", id: null, error: { code: -32700, message: "parse error" } });
      return;
    }
    const resp = await dispatch(msg);
    if (resp !== undefined) reply(resp);
  })().catch((e) => {
    console.error("oj mcp: internal error: " + (e && e.stack ? e.stack : e));
  });
});
console.error("oj mcp: " + SERVER_NAME + " ready (OJ_BASE=" + BASE_URL + ", " + TOOLS.length + " tools)");
"#;

/// 渲染纯函数（不碰盘，便于单测）。`tenant_header`：config 声明的租户头名
///（非密钥）；None = 不生成租户头分支。
pub fn render_server(
    tools: &[serve::mcp::McpTool],
    spec_hash: &str,
    base: &str,
    tenant_header: Option<&str>,
) -> String {
    let tools_json =
        serde_json::to_string(&tools.iter().map(|t| t.tool.clone()).collect::<Vec<Value>>())
            .expect("tool JSON 序列化");
    let mut dispatch = serde_json::Map::new();
    for t in tools {
        dispatch.insert(
            t.name.clone(),
            json!({
                "method": t.dispatch.method,
                "path": t.dispatch.oa_path,
                "operationId": t.dispatch.operation_id,
                "catchAll": t.dispatch.catch_all,
            }),
        );
    }
    let dispatch_json = serde_json::to_string(&Value::Object(dispatch)).expect("dispatch 序列化");
    let tenant_js = match tenant_header {
        Some(h) => format!(
            "const TENANT_HEADER = {};",
            serde_json::to_string(h).unwrap()
        ),
        None => "const TENANT_HEADER = null;".to_string(),
    };
    TEMPLATE
        .replace("__TOOLS_JSON__", &tools_json)
        .replace("__DISPATCH_JSON__", &dispatch_json)
        .replace("__BASE_PATH__", base)
        .replace("__TENANT_HEADER__", &tenant_js)
        .replace("__HASH8__", spec_hash.get(..8).unwrap_or(spec_hash))
        .replace("__HASH__", spec_hash)
}

/// spec JSON 的确定性短散列（fnv1a64 复用 serve::mcp，标注用，非密码学）。
fn spec_hash(spec: &Value) -> String {
    let s = serde_json::to_string(spec).unwrap_or_default();
    format!("{:016x}", serve::mcp::fnv1a64(s.as_bytes()))
}

/// 命令入口：发现路由 → spec → tools → 渲染落盘。返回进程退出码。
pub async fn run(a: &McpArgs) -> Result<i32, String> {
    let loaded = crate::serve_cmd::load_app_config(
        a.config.as_deref(),
        a.site.as_deref(),
        a.dir.as_deref(),
        a.base.as_deref(),
        true,
        a.module_root.as_deref(),
    )?;
    let crate::serve_cmd::AppConfig {
        cfg,
        dir,
        ts,
        base,
        module_index,
        config_dir,
        ..
    } = loaded;

    let table =
        crate::openapi_cmd::discover_routes(&dir, &config_dir, ts, &base, module_index.as_deref())?;
    let spec = crate::openapi_cmd::generate(&table, &base)?;
    let mut tools = serve::mcp::spec_to_tools(&spec)?;
    // 回补 catch-all 参数名（spec 已收敛 `{x}`，须按路由表 raw pattern 判定）。
    for t in &mut tools {
        if let Some(raw) =
            serve::mcp_http::raw_pattern_for(&table, &t.dispatch.oa_path, &t.dispatch.method)
        {
            t.dispatch.catch_all = raw
                .split('/')
                .filter_map(|s| s.strip_prefix("{*").and_then(|x| x.strip_suffix('}')))
                .map(str::to_string)
                .collect();
        }
    }
    // 租户头名（非密钥）：tenant 未启用或未配头名 → None（模板不生成该分支）。
    let tenant_header = (cfg.tenant.enable && !cfg.tenant.header_key.is_empty())
        .then(|| cfg.tenant.header_key.clone());
    let hash = spec_hash(&spec);
    let js = render_server(&tools, &hash, &base, tenant_header.as_deref());

    let out_path: PathBuf = a
        .out
        .clone()
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("mcp/mcp-server.js"));
    if let Some(parent) = out_path.parent() {
        std::fs::create_dir_all(parent).map_err(|e| format!("create {}: {e}", parent.display()))?;
    }
    std::fs::write(&out_path, format!("{js}\n"))
        .map_err(|e| format!("write {}: {e}", out_path.display()))?;
    eprintln!(
        "oj mcp: wrote {} ({} tools, spec_hash {hash})",
        out_path.display(),
        tools.len()
    );
    Ok(0)
}

#[cfg(test)]
mod tests {
    use super::*;
    use serve::mcp::{McpTool, ToolDispatch};

    fn tool(name: &str, oa_path: &str, catch_all: Vec<&str>) -> McpTool {
        McpTool {
            name: name.into(),
            tool: json!({
                "name": name,
                "description": format!("OP {name}"),
                "inputSchema": { "type": "object", "properties": {} },
            }),
            dispatch: ToolDispatch {
                operation_id: name.replace('-', "."),
                method: "get".into(),
                oa_path: oa_path.into(),
                catch_all: catch_all.iter().map(|s| s.to_string()).collect(),
            },
        }
    }

    // Given 两个 tool（其一 catch-all）
    // When render_server
    // Then 产物含两 dispatch 表项；catch-all 参数走 decodeURI 分支（fillPath 有该分支），
    //      且 catchAll 名单随 dispatch 内嵌
    #[test]
    fn render_embeds_tool_map_with_catchall_branch() {
        let tools = vec![
            tool("a_get", "/v1/api/a/{id}", vec![]),
            tool("b_get", "/v1/api/b/{*path}", vec!["path"]),
        ];
        let js = render_server(&tools, "0123456789abcdef", "/v1/api", None);
        assert!(
            js.contains(r#""a_get":{"method":"get","path":"/v1/api/a/{id}""#),
            "{js}"
        );
        assert!(
            js.contains(r#""b_get":{"method":"get","path":"/v1/api/b/{*path}""#),
            "{js}"
        );
        assert!(js.contains(r#""catchAll":["path"]"#), "{js}");
        // catch-all 分支存在（decodeURI）且单段编码存在（encodeURIComponent）
        assert!(js.contains("decodeURI(String(v))"), "{js}");
        assert!(js.contains("encodeURIComponent(String(v))"), "{js}");
    }

    // Given 渲染产物
    // Then 诊断只走 stderr（console.error），stdout 无 console.log 污染
    #[test]
    fn generated_script_never_writes_stdout_logs() {
        let js = render_server(
            &[tool("a_get", "/a", vec![])],
            "0123456789abcdef",
            "/v1/api",
            None,
        );
        assert!(js.contains("console.error"), "{js}");
        assert!(!js.contains("console.log"), "{js}");
    }

    // Given 渲染产物
    // Then 实现 structuredContent / isError / AbortSignal.timeout（结果形态纪律）
    #[test]
    fn generated_script_implements_result_and_error_shapes() {
        let js = render_server(
            &[tool("a_get", "/a", vec![])],
            "0123456789abcdef",
            "/v1/api",
            None,
        );
        assert!(js.contains("structuredContent"), "{js}");
        assert!(js.contains("isError"), "{js}");
        assert!(js.contains("AbortSignal.timeout(30000)"), "{js}");
    }

    // Given 渲染产物
    // Then fetch 硬化（redirect manual）+ OJ_TENANT env 消费 + Bearer/明文警告在位
    #[test]
    fn generated_script_hardens_fetch_and_supports_tenant_header() {
        let js = render_server(
            &[tool("a_get", "/a", vec![])],
            "0123456789abcdef",
            "/v1/api",
            None,
        );
        assert!(js.contains(r#"redirect: "manual""#), "{js}");
        assert!(js.contains("OJ_TENANT"), "{js}");
        // 未配置租户 → TENANT_HEADER 为 null
        assert!(js.contains("const TENANT_HEADER = null;"), "{js}");
        // 配置租户 → 头名内嵌
        let js = render_server(
            &[tool("a_get", "/a", vec![])],
            "0123456789abcdef",
            "/v1/api",
            Some("x-tenant-id"),
        );
        assert!(
            js.contains(r#"const TENANT_HEADER = "x-tenant-id";"#),
            "{js}"
        );
        // Bearer 明文 http:// 警告
        assert!(js.contains("cleartext"), "{js}");
        assert!(js.contains("OJ_TOKEN"), "{js}");
    }

    // Given spec
    // Then spec_hash 确定性（同输入同输出，fnv1a64 十六进制）
    #[test]
    fn spec_hash_is_deterministic() {
        let s = json!({ "paths": { "/a": { "get": { "operationId": "a_get" } } } });
        let h1 = spec_hash(&s);
        let h2 = spec_hash(&s);
        assert_eq!(h1, h2);
        assert_eq!(h1.len(), 16);
        assert_ne!(h1, spec_hash(&json!({ "paths": {} })));
    }

    // Given 渲染产物
    // Then 方法集齐备 + batch 拒绝 + 通知不回写 + 协议协商回退
    #[test]
    fn generated_script_covers_protocol_surface() {
        let js = render_server(
            &[tool("a_get", "/a", vec![])],
            "0123456789abcdef",
            "/v1/api",
            None,
        );
        for m in [
            "\"initialize\"",
            "\"ping\"",
            "\"tools/list\"",
            "\"tools/call\"",
            "-32600",
            "-32700",
            "-32601",
            "notifications/",
            "protocolVersion",
            "capabilities",
            "serverInfo",
            "batch not supported",
        ] {
            assert!(js.contains(m), "缺 {m}: {js}");
        }
    }
}
