/// stdio server 模板。`__TOKEN__` 占位替换（不引模板引擎）；JS 里的 `{}` 因此
/// 无需转义。ASCII only。
const TEMPLATE: &str = r#"#!/usr/bin/env node
// Generated by `oj mcp` -- do not edit.
// api base path: __BASE_PATH__   spec_hash: __HASH__
// regen: oj mcp -c <config> [-d <dir>|--module-root <root>] [--base B] [-o <file>]
// env: OJ_BASE (required, e.g. http://localhost:9778) | OJ_TOKEN (Bearer, optional)
//      OJ_TENANT (tenant header value, only if the server config declares a tenant header)
"use strict";

const SUPPORTED = ["2024-11-05", "2025-03-26", "2025-06-18"];
const SPEC_HASH = "__HASH__";
const SERVER_NAME = "oj-mcp-__HASH8__";
const TOOLS = __TOOLS_JSON__;
const DISPATCH = __DISPATCH_JSON__;
const EXPOSE = "__EXPOSE__";
const GROUPS = __GROUPS_JSON__;
const META = __META_JSON__;
// 元工具名以 META 为单一来源（注入自 serve::mcp::meta_tool_defs）：拦截与分发
// 按名单派生——新增元工具只需改 Rust 侧 defs 并在此补实现分支，不得另写名单。
function isMetaName(name) { return META.some(function (t) { return t.name === name; }); }
__TENANT_HEADER__

const BASE_URL = process.env.OJ_BASE;
if (!BASE_URL) {
  console.error("oj mcp: OJ_BASE is required (e.g. http://localhost:9778)");
  process.exit(2);
}
if (/^http:\/\//.test(BASE_URL) && !/^http:\/\/(localhost|127\.0\.0\.1|\[::1\])(:|\/|$)/.test(BASE_URL)) {
  console.error("oj mcp: WARNING - OJ_BASE is plain http:// on a non-localhost host;" +
    " the Bearer token (OJ_TOKEN) will travel in cleartext.");
}
const TOKEN = process.env.OJ_TOKEN || "";
let tenantWarned = false;

function reply(r) { process.stdout.write(JSON.stringify(r) + "\n"); }

function fillPath(tmpl, args, catchAll) {
  const segs = [];
  for (const seg of tmpl.split("/")) {
    if (!seg) continue;
    const m = /^\{(.+)\}$/.exec(seg);
    if (m) {
      const name = m[1];
      const v = args == null ? undefined : args[name];
      if (v === undefined || v === null) {
        throw { code: -32602, message: "missing path argument: " + name };
      }
      // catch-all 也逐段编码（终审 major：原样插入会让 `..`/`?` 经 URL 归一化
      // 逃出 tool 前缀或走私 query）；跨段 `/` 保留为真实分隔符。
      segs.push(
        catchAll.has(name)
          ? String(v).split("/").map((s) => encodeURIComponent(s)).join("/")
          : encodeURIComponent(String(v))
      );
    } else {
      segs.push(seg);
    }
  }
  return "/" + segs.join("/");
}

function buildQuery(args) {
  const qs = new URLSearchParams();
  if (args && typeof args.query === "object" && args.query) {
    for (const [k, v] of Object.entries(args.query)) qs.append(k, String(v));
  }
  const s = qs.toString();
  return s ? "?" + s : "";
}

// 本地检索（L2 routed，与 serve::mcp_http::search_tools 同钉共享向量语义）：
// 大小写不敏感子串可叠加 name=2/description=1/group(tags[0])=1；score desc +
// name asc；limit 缺省 10 钳 50；match 项同键集（group/annotations 无则缺席）。
// 离线快照无展示裁剪概念——全集即展示集（线路 A 静态产物，act/scopes 在执行侧）。
function searchTools(query, group, limit) {
  const q = String(query).toLowerCase();
  const lim = Math.min(limit == null || !Number.isFinite(+limit) ? 10 : Math.max(1, Math.trunc(+limit)), 50);
  const scored = [];
  for (const t of TOOLS) {
    const tag = Array.isArray(t.tags) && t.tags.length ? String(t.tags[0]) : null;
    if (group != null && tag !== String(group)) continue;
    let score = 0;
    if (String(t.name).toLowerCase().indexOf(q) >= 0) score += 2;
    if (String(t.description || "").toLowerCase().indexOf(q) >= 0) score += 1;
    if (tag != null && tag.toLowerCase().indexOf(q) >= 0) score += 1;
    if (score > 0) scored.push([score, t, tag]);
  }
  scored.sort((a, b) => b[0] - a[0] || (a[1].name < b[1].name ? -1 : a[1].name > b[1].name ? 1 : 0));
  const matches = [];
  for (const m of scored.slice(0, lim)) {
    const t = m[1];
    const item = {
      name: t.name,
      description: t.description == null ? null : t.description,
      inputSchema: t.inputSchema || { type: "object" },
    };
    if (m[2] != null) item.group = m[2];
    if (t.annotations != null) item.annotations = t.annotations;
    matches.push(item);
  }
  return { matches };
}

// 元工具执行（L2 routed）：命中日志与 serve search_log_line 同字段（命中率分析），
// 诊断走 stderr 不破 stdout 纯净纪律。query/limit 口径与 serve run_meta_tool 逐字对齐：
// 空 query 拒（-32602 载体为 isError；空串是任意串子串，不拦则 routed 一次 call
// 拉平全目录——review S1）；limit 仅 JSON 整数参与钳制（3.5/"5" → 缺省 10），
// 先钳 0..50（searchTools 下限钳 1），日志记钳后值；group 日志为 Rust Debug 形
// Some("x")/None。
function callMeta(name, args) {
  if (!isMetaName(name)) {
    return { isError: true, content: [{ type: "text", text: "unknown tool: " + name }] };
  }
  if (name === "oj_search_tools") {
    if (!args || typeof args.query !== "string") {
      return { isError: true, content: [{ type: "text", text: "params.arguments.query must be a string" }] };
    }
    if (args.query.length === 0) {
      return { isError: true, content: [{ type: "text", text: "params.arguments.query must be a non-empty string" }] };
    }
    const started = Date.now();
    // 非字符串 group 与 serve 同口径：忽略过滤（serve 侧 as_str → None）。
    const grp = typeof args.group === "string" ? args.group : null;
    const raw = args.limit;
    const lim = (typeof raw === "number" && Number.isInteger(raw)) ? Math.min(Math.max(raw, 0), 50) : 10;
    const result = searchTools(args.query, grp, lim);
    console.error("mcp search: query=" + JSON.stringify(args.query) +
      " group=" + (grp == null ? "None" : "Some(" + JSON.stringify(grp) + ")") +
      " limit=" + lim +
      " returned=" + result.matches.length +
      " zero=" + (result.matches.length === 0) +
      " elapsed_ms=" + (Date.now() - started));
    return { content: [{ type: "text", text: JSON.stringify(result) }], structuredContent: result };
  }
  if (name === "oj_list_groups") {
    const result = { groups: GROUPS };
    return { content: [{ type: "text", text: JSON.stringify(result) }], structuredContent: result };
  }
  return { isError: true, content: [{ type: "text", text: "meta tool not implemented: " + name }] };
}

async function callTool(name, args) {
  // 元工具名在 DISPATCH 查找**之前**短路（同 serve call_tool 短路序；名单来自
  // META 单源派生）——业务 tool（含 oj_market_* 等 oj_ 前缀名）不得被劫持。
  if (isMetaName(name)) return callMeta(name, args);
  const d = DISPATCH[name];
  if (!d) return { isError: true, content: [{ type: "text", text: "unknown tool: " + name }] };
  let path;
  try {
    path = fillPath(d.path, args, new Set(d.catchAll || []));
  } catch (e) {
    return { isError: true, content: [{ type: "text", text: e.message } ] };
  }
  const headers = { accept: "application/json" };
  let body;
  if (args && args.body !== undefined) {
    headers["content-type"] = "application/json";
    body = JSON.stringify(args.body);
  }
  if (TOKEN) headers["authorization"] = "Bearer " + TOKEN;
  if (TENANT_HEADER) {
    const t = process.env.OJ_TENANT;
    if (t) headers[TENANT_HEADER] = t;
    else if (!tenantWarned) {
      tenantWarned = true;
      console.error("oj mcp: tenant header " + TENANT_HEADER + " configured but OJ_TENANT is not set" +
        " - sending without tenant header");
    }
  }
  let res;
  try {
    res = await fetch(BASE_URL + path + buildQuery(args), {
      method: d.method.toUpperCase(),
      headers,
      body,
      redirect: "manual",
      signal: AbortSignal.timeout(30000),
    });
  } catch (e) {
    return { isError: true, content: [{ type: "text", text: "transport error: " + (e && e.message ? e.message : e) }] };
  }
  const ct = res.headers.get("content-type") || "";
  if (ct.includes("text/event-stream")) {
    try { if (res.body) await res.body.cancel(); } catch (_) { /* best effort */ }
    return { isError: true, content: [{ type: "text", text: "streaming endpoint, not supported via MCP" }] };
  }
  const text = await res.text();
  let parsed = null;
  try { parsed = JSON.parse(text); } catch (_) { /* raw text below */ }
  // 与 Rust 侧 is_envelope 逐字同口径（终审 minor：data 键必在，防业务对象误判）。
  if (parsed && typeof parsed === "object" && typeof parsed.code === "number" &&
      typeof parsed.msg === "string" && "data" in parsed) {
    if (parsed.code === 0) {
      const data = parsed.data === undefined ? null : parsed.data;
      return {
        content: [{ type: "text", text: typeof data === "string" ? data : JSON.stringify(data, null, 2) }],
        structuredContent: data,
      };
    }
    return { isError: true, content: [{ type: "text", text: parsed.msg }] };
  }
  return { content: [{ type: "text", text }] };
}

async function dispatch(msg) {
  if (Array.isArray(msg)) {
    // MCP 2025-06-18 移除 batch：-32600（非法请求）。
    return { jsonrpc: "2.0", id: null, error: { code: -32600, message: "batch not supported" } };
  }
  if (!msg || msg.jsonrpc !== "2.0" || typeof msg.method !== "string") {
    return { jsonrpc: "2.0", id: msg && "id" in msg ? msg.id : null, error: { code: -32600, message: "invalid request" } };
  }
  const isNotify = msg.id === undefined;
  const err = (code, message) => ({ jsonrpc: "2.0", id: "id" in msg ? msg.id : null, error: { code, message } });
  switch (msg.method) {
    case "initialize": {
      if (isNotify) return undefined;
      const pv = msg.params && msg.params.protocolVersion;
      const negotiated = SUPPORTED.indexOf(pv) >= 0 ? pv : SUPPORTED[SUPPORTED.length - 1];
      return {
        jsonrpc: "2.0",
        id: msg.id,
        result: {
          protocolVersion: negotiated,
          capabilities: { tools: {} },
          serverInfo: { name: SERVER_NAME, version: SPEC_HASH },
        },
      };
    }
    case "ping":
      return isNotify ? undefined : { jsonrpc: "2.0", id: msg.id, result: {} };
    case "tools/list": {
      if (isNotify) return undefined;
      // L1/L2 三模式列表面（spec 2026-11-12）：routed 只回元工具（spec 允许
      // call 名不在 list 内，客户端策略差异）；grouped 在 _meta 扩展位带分组面
      // （严格客户端 FAIL_ON_UNKNOWN 安全——不在 result 顶层加键）；flat 不变。
      if (EXPOSE === "routed") return { jsonrpc: "2.0", id: msg.id, result: { tools: META } };
      if (EXPOSE === "grouped") {
        return { jsonrpc: "2.0", id: msg.id, result: { tools: TOOLS, _meta: { "com.only-js.groups": GROUPS } } };
      }
      return { jsonrpc: "2.0", id: msg.id, result: { tools: TOOLS } };
    }
    case "tools/call": {
      const r = await callTool(msg.params && msg.params.name, msg.params && msg.params.arguments);
      return isNotify ? undefined : { jsonrpc: "2.0", id: msg.id, result: r };
    }
    default:
      if (msg.method.lastIndexOf("notifications/", 0) === 0) return undefined;
      return err(-32601, "method not found: " + msg.method);
  }
}

const rl = require("node:readline").createInterface({ input: process.stdin });
rl.on("line", (line) => {
  (async () => {
    let msg = null;
    try { msg = JSON.parse(line); } catch (_) { /* parse error below */ }
    if (msg === null) {
      reply({ jsonrpc: "2.0", id: null, error: { code: -32700, message: "parse error" } });
      return;
    }
    const resp = await dispatch(msg);
    if (resp !== undefined) reply(resp);
  })().catch((e) => {
    console.error("oj mcp: internal error: " + (e && e.stack ? e.stack : e));
  });
});
console.error("oj mcp: " + SERVER_NAME + " ready (OJ_BASE=" + BASE_URL + ", " + TOOLS.length + " tools)");
"#;

/// ExposeMode → 模板内嵌小写串（词表与 config serde lowercase 同；不依赖 Debug）。
fn expose_str(e: &serve::mcp::ExposeMode) -> &'static str {
    match e {
        serve::mcp::ExposeMode::Flat => "flat",
        serve::mcp::ExposeMode::Grouped => "grouped",
        serve::mcp::ExposeMode::Routed => "routed",
    }
}

/// 渲染纯函数（不碰盘，便于单测）。`tenant_header`：config 声明的租户头名
///（非密钥）；None = 不生成租户头分支。`groups`：L1 grouped 的 _meta 分组面
///（`build_groups` 产物）；`expose`：三模式列表面（模板 EXPOSE 占位）。
pub fn render_server(
    tools: &[serve::mcp::McpTool],
    spec_hash: &str,
    base: &str,
    tenant_header: Option<&str>,
    expose: serve::mcp::ExposeMode,
    groups: &Value,
) -> String {
    let tools_json =
        serde_json::to_string(&tools.iter().map(|t| t.tool.clone()).collect::<Vec<Value>>())
            .expect("tool JSON 序列化");
    let mut dispatch = serde_json::Map::new();
    for t in tools {
        dispatch.insert(
            t.name.clone(),
            json!({
                "method": t.dispatch.method,
                "path": t.dispatch.oa_path,
                "operationId": t.dispatch.operation_id,
                "catchAll": t.dispatch.catch_all,
            }),
        );
    }
    let dispatch_json = serde_json::to_string(&Value::Object(dispatch)).expect("dispatch 序列化");
    // 元工具定义逐字注入（与 serve::mcp::meta_tool_defs 单一来源——模板内联不漂移）。
    let meta_json = serde_json::to_string(&serve::mcp::meta_tool_defs()).expect("meta defs 序列化");
    let groups_json = serde_json::to_string(groups).expect("groups 序列化");
    let tenant_js = match tenant_header {
        Some(h) => format!(
            "const TENANT_HEADER = {};",
            serde_json::to_string(h).unwrap()
        ),
        None => "const TENANT_HEADER = null;".to_string(),
    };
    // 替换顺序有讲究（终审 minor）：token 先行、tools/dispatch 最后——tool 描述里
    // 的字面 __HASH__ 不会被后续 replace 改写。
    TEMPLATE
        .replace("__BASE_PATH__", base)
        .replace("__TENANT_HEADER__", &tenant_js)
        .replace("__HASH8__", spec_hash.get(..8).unwrap_or(spec_hash))
        .replace("__HASH__", spec_hash)
        .replace("__EXPOSE__", expose_str(&expose))
        .replace("__GROUPS_JSON__", &groups_json)
        .replace("__META_JSON__", &meta_json)
        .replace("__TOOLS_JSON__", &tools_json)
        .replace("__DISPATCH_JSON__", &dispatch_json)
}

/// spec JSON 的确定性短散列（fnv1a64 复用 serve::mcp，标注用，非密码学）。
fn spec_hash(spec: &Value) -> String {
    let s = serde_json::to_string(spec).unwrap_or_default();
    format!("{:016x}", serve::mcp::fnv1a64(s.as_bytes()))
}

/// 命令入口：发现路由 → spec → tools → 渲染落盘。返回进程退出码。
pub async fn run(a: &McpArgs) -> Result<i32, String> {
    let loaded = crate::serve_cmd::load_app_config(
        a.config.as_deref(),
        a.site.as_deref(),
        a.dir.as_deref(),
        a.base.as_deref(),
        true,
        a.module_root.as_deref(),
    )?;
    let crate::serve_cmd::AppConfig {
        cfg,
        dir,
        ts,
        base,
        module_index,
        config_dir,
        ..
    } = loaded;

    let table =
        crate::openapi_cmd::discover_routes(&dir, &config_dir, ts, &base, module_index.as_deref())?;
    let spec = crate::openapi_cmd::generate(&table, &base)?;
    let tools = serve::mcp::spec_to_tools(&spec)?;
    // modules 白名单两线对齐（review #3/#7，v0.1.135）：codegen 与 serve 请求期
    // tools_for / 装配期保留名扫描共用同一份 apply_modules_filter——产物只含白名单
    // 模块（配置的暴露限制在 stdio 产物里不被静默放大）；保留名检查也在裁剪后
    // 集合上跑，被排除模块不参与校验（与 oj serve 同口径，不得一边放行一边拒）。
    let mut tools = serve::mcp::apply_modules_filter(
        tools,
        cfg.server.mcp.as_ref().and_then(|m| m.modules.as_ref()),
    );
    // 回补 catch-all 参数名（spec 已收敛 `{x}`，须按路由表 raw pattern 判定）。
    for t in &mut tools {
        if let Some(raw) =
            serve::mcp_http::raw_pattern_for(&table, &t.dispatch.oa_path, &t.dispatch.method)
        {
            t.dispatch.catch_all = raw
                .split('/')
                .filter_map(|s| s.strip_prefix("{*").and_then(|x| x.strip_suffix('}')))
                .map(str::to_string)
                .collect();
        }
    }
    // 租户头名（非密钥）：tenant 未启用或未配头名 → None（模板不生成该分支）。
    let tenant_header = (cfg.tenant.enable && !cfg.tenant.header_key.is_empty())
        .then(|| cfg.tenant.header_key.clone());
    let hash = spec_hash(&spec);
    // 元工具保留名 fail-fast（spec 2026-11-12；v0.1.135 收窄为精确名判定且在
    // modules 白名单裁剪后集合上跑）：与 serve 装配同标准，产物不静默撞名。
    serve::mcp::check_reserved_names(&tools)?;
    // L1/L2 模式决议（spec 2026-11-12）：CLI --expose 覆盖 config server.mcp.expose，
    // 缺省 flat（零破坏）。分组面 = 全量 tools 聚合（线路 A 静态快照无展示裁剪）。
    let expose = a.expose.unwrap_or(
        match cfg.server.mcp.as_ref().and_then(|m| m.expose.as_ref()) {
            Some(only_js::config::ExposeCfg::Grouped) => serve::mcp::ExposeMode::Grouped,
            Some(only_js::config::ExposeCfg::Routed) => serve::mcp::ExposeMode::Routed,
            _ => serve::mcp::ExposeMode::Flat,
        },
    );
    let groups = serve::mcp_http::build_groups(&tools.iter().collect::<Vec<_>>());
    let js = render_server(
        &tools,
        &hash,
        &base,
        tenant_header.as_deref(),
        expose,
        &groups,
    );

    let out_path: PathBuf = a
        .out
        .clone()
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("mcp/mcp-server.js"));
    if let Some(parent) = out_path.parent() {
        std::fs::create_dir_all(parent).map_err(|e| format!("create {}: {e}", parent.display()))?;
    }
    std::fs::write(&out_path, format!("{js}\n"))
        .map_err(|e| format!("write {}: {e}", out_path.display()))?;
    eprintln!(
        "oj mcp: wrote {} ({} tools, spec_hash {hash}, expose {})",
        out_path.display(),
        tools.len(),
        expose_str(&expose),
    );
    Ok(0)
}

